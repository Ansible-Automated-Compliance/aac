#!/usr/bin/env python3
"""Regenerate ansible/ao/components.yml from ansible/ao/workflows/*.json.

The manifest has three top-level keys:

  provenance        where/when the JSON was exported and which lab versions it
                    captures; plus `changes_since_export`, the edits made in git
                    after the export (the lab AO holds the older definition
                    until it is re-imported). Hand-maintained, preserved verbatim.
  environment_ids   every environment-specific UUID the workflow JSON embeds
                    (AO integrations, AO credentials, LLM models), with the
                    human name a loader resolves on a fresh environment. The
                    id -> name/type mapping is hand-maintained and preserved;
                    the `used_by` lists are derived from the JSON on every run.
                    A UUID the JSON uses that has no entry yet is added with
                    `name: null` so the gap is visible, not silent.
  ao_workflows      per-workflow dependency summary — fully derived, including
                    `agentic_tool_access` (per agentic node: which MCP tools it
                    may call, whether its prompt reads job-published set_stats,
                    whether its output is posted to an OPA policy) and the
                    `security_note` that travels with every MCP-attached agent.

Usage:
    python3 scripts/ao_components.py            # rewrite the manifest
    python3 scripts/ao_components.py --check    # exit 1 if it would change

Only the standard library plus PyYAML (already required by ansible) is used.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
AO_DIR = ROOT / "ansible" / "ao"
WF_DIR = AO_DIR / "workflows"
MANIFEST = AO_DIR / "components.yml"

HEADER = """\
---
# Component manifest for the AAC Automation Orchestrator workflows.
# GENERATED by scripts/ao_components.py from workflows/*.json — edit only the
# `provenance` block and the id -> name/type fields under `environment_ids`
# (they cannot be derived from the JSON); everything else is rewritten on each
# run. The UUIDs below are AO object identifiers from the lab, not secrets: a
# loader replaces every one of them with the target environment's own ID,
# resolved by name (see README.md).
"""


class _Dumper(yaml.SafeDumper):
    """Indent list items under their parent key (what ansible-lint expects)."""

    def increase_indent(self, flow=False, indentless=False):  # noqa: D401
        return super().increase_indent(flow, False)


def _dump(data: dict) -> str:
    return HEADER + yaml.dump(
        data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100, default_flow_style=False
    )


def _load_existing() -> dict:
    if not MANIFEST.exists():
        return {}
    return yaml.safe_load(MANIFEST.read_text(encoding="utf-8")) or {}


def _entrypoint(url: str) -> str:
    marker = "/v1/data/"
    return url.split(marker, 1)[1] if marker in url else url


SECURITY_NOTE = (
    "agentic nodes must attach a READ-ONLY MCP server; the policy (opa-routing) decides, "
    "the agent only recommends"
)
_ARTIFACT_REF = re.compile(r"\$\{([A-Za-z0-9_]+)\.artifacts\.")


def _mcp_tools(params: dict):
    """What the agent may call: "ALL", the explicit tool list, or "none"."""
    if not params.get("integration_connections"):
        return "none"
    strategy = params.get("tool_selection_strategy")
    if strategy == "ALL":
        return "ALL"
    tools = sorted({t for conn in params["integration_connections"] for t in (conn.get("tools") or [])})
    return tools or (strategy or "unspecified")


def _agentic_tool_access(nodes: list[dict], agentic: list[dict]) -> list[dict]:
    """Per agentic node: tool reach, whether the prompt reads host-published
    set_stats (`${<job>.artifacts.*}` — text the managed host controls), and
    whether any http_request posts the agent's result to a policy."""
    job_ids = {n["id"] for n in nodes if n.get("type") in ("aap_job_template", "aap_workflow_job_template")}
    policy_bodies = json.dumps([n.get("parameters", {}).get("body") for n in nodes if n.get("type") == "http_request"])
    out = []
    for n in agentic:
        params = n.get("parameters", {})
        sources = sorted({src for src in _ARTIFACT_REF.findall(params.get("prompt", "")) if src in job_ids})
        out.append({
            "node": n["name"],
            "mcp_tools": _mcp_tools(params),
            "reads_host_published_facts": bool(sources),
            "host_fact_sources": sources,
            "output_feeds_policy": f"${{{n['id']}." in policy_bodies,
        })
    return out


def _summarise(path: Path, definition: dict, lab_versions: dict) -> tuple[str, dict, dict]:
    nodes = definition.get("nodes", [])
    triggers = definition.get("triggers", [])
    by_type: dict[str, list[dict]] = {}
    for node in nodes:
        by_type.setdefault(node.get("type", "?"), []).append(node)

    trigger_inputs: list[str] = []
    for trigger in triggers:
        schema = trigger.get("parameters", {}).get("input_schema", {})
        for key in schema.get("properties", {}):
            if key not in trigger_inputs:
                trigger_inputs.append(key)

    agentic = by_type.get("agentic", [])
    summary = {
        "file": f"workflows/{path.name}",
        "lab_version": lab_versions.get(definition["name"]),
        "nodes": len(nodes),
        "edges": len(definition.get("edges", [])),
        "trigger": [t.get("type") for t in triggers],
        "trigger_inputs": trigger_inputs,
        "aap_job_templates": sorted({n["parameters"]["job_template_name"] for n in by_type.get("aap_job_template", [])}),
        "aap_workflow_templates": sorted(
            {n["parameters"]["workflow_job_template_name"] for n in by_type.get("aap_workflow_job_template", [])}
        ),
        "opa_routing_entrypoints": sorted({_entrypoint(n["parameters"]["url"]) for n in by_type.get("http_request", [])}),
        "uses_llm": bool(agentic),
        "llm_model_ids": sorted({n["parameters"]["llm_model_id"] for n in agentic if n["parameters"].get("llm_model_id")}),
        "uses_mcp_tools": any(n["parameters"].get("integration_connections") for n in agentic),
        "agentic_nodes_without_mcp": sorted(n["id"] for n in agentic if not n["parameters"].get("integration_connections")),
        "approvals": len(by_type.get("approval", [])),
        "switch_or_converge_nodes": len(by_type.get("switch", [])) + len(by_type.get("converge", [])),
    }
    if agentic:
        summary["agentic_tool_access"] = _agentic_tool_access(nodes, agentic)
    if summary["uses_mcp_tools"]:
        summary["security_note"] = SECURITY_NOTE

    # Environment-specific UUIDs this workflow embeds.
    refs: dict[str, dict[str, set]] = {"integrations": {}, "credentials": {}, "llm_models": {}}

    def ref(kind: str, uuid: str, where: str) -> None:
        if uuid:
            refs[kind].setdefault(uuid, set()).add(where)

    slug = path.stem
    for node in nodes:
        params = node.get("parameters", {})
        where = f"{slug}:{node['id']}"
        ref("integrations", params.get("integration_id"), where)
        ref("credentials", params.get("credential_id"), where)
        ref("llm_models", params.get("llm_model_id"), where)
        for conn in params.get("integration_connections") or []:
            ref("integrations", conn.get("integration_id"), where)
            ref("credentials", conn.get("credential_id"), where)
    return definition["name"], summary, refs


def _merge_ids(existing: dict, refs: dict[str, dict[str, set]]) -> dict:
    """Keep hand-maintained name/type fields, rewrite the derived used_by lists."""
    out: dict[str, list[dict]] = {}
    for kind in ("integrations", "credentials", "llm_models"):
        known = {e["id"]: e for e in (existing.get(kind) or [])}
        entries = []
        # A hand-listed ID the JSON never references directly (the LLM provider
        # integration is implied by its credential and models) is kept with an
        # empty used_by, so the loader still knows the component must exist.
        uuids = set(refs[kind]) | set(known)
        for uuid in sorted(uuids, key=lambda u: (known.get(u, {}).get("name") or "~", u)):
            entry = {"id": uuid}
            prior = known.get(uuid, {})
            for field in ("name", "type", "integration", "model"):
                if field in prior:
                    entry[field] = prior[field]
            if "name" not in entry:
                entry["name"] = None
            used = sorted(refs[kind].get(uuid, set()))
            # Integrations/credentials are used in many nodes; list workflows.
            # Models are per node — the Mythos agents deliberately differ.
            if kind == "llm_models":
                entry["used_by_nodes"] = used
            else:
                entry["used_by"] = sorted({u.split(":", 1)[0] for u in used})
            entries.append(entry)
        out[kind] = entries
    return out


def build() -> str:
    existing = _load_existing()
    provenance = existing.get("provenance") or {}
    lab_versions = provenance.get("lab_versions") or {}

    workflows: dict[str, dict] = {}
    all_refs: dict[str, dict[str, set]] = {"integrations": {}, "credentials": {}, "llm_models": {}}
    for path in sorted(WF_DIR.glob("*.json")):
        definition = json.loads(path.read_text(encoding="utf-8"))
        name, summary, refs = _summarise(path, definition, lab_versions)
        workflows[name] = summary
        for kind, uuids in refs.items():
            for uuid, where in uuids.items():
                all_refs[kind].setdefault(uuid, set()).update(where)

    manifest = {
        "provenance": provenance,
        "environment_ids": _merge_ids(existing.get("environment_ids") or {}, all_refs),
        "ao_workflows": workflows,
    }
    return _dump(manifest)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if components.yml is not up to date")
    args = parser.parse_args()

    rendered = build()
    current = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
    if args.check:
        if rendered != current:
            print(f"{MANIFEST.relative_to(ROOT)} is stale — run scripts/ao_components.py", file=sys.stderr)
            return 1
        print(f"{MANIFEST.relative_to(ROOT)} is up to date")
        return 0
    MANIFEST.write_text(rendered, encoding="utf-8")
    unnamed = [e["id"] for kind in ("integrations", "credentials", "llm_models") for e in yaml.safe_load(rendered)["environment_ids"][kind] if not e.get("name")]
    print(f"wrote {MANIFEST.relative_to(ROOT)}: {len(yaml.safe_load(rendered)['ao_workflows'])} workflows")
    if unnamed:
        print("environment_ids with no name yet (fill by hand): " + ", ".join(unnamed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
