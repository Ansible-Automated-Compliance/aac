#!/usr/bin/env python3
"""Write the weekly AAC update: what was merged to main in a date window.

The update is built from merged pull requests, so it lists what is on main,
not what is planned. Each pull request title becomes one line under a heading
chosen from its conventional-commit prefix (feat, fix, docs, ...). Dependency
bumps are counted, not listed.

    # the seven days ending today (UTC), written to docs/updates/<until>.md
    python3 scripts/weekly_update.py

    # a chosen window
    python3 scripts/weekly_update.py --since 2026-11-17 --until 2026-11-24

    # print instead of writing; or build from a saved `gh pr list --json` file
    python3 scripts/weekly_update.py --stdout
    python3 scripts/weekly_update.py --from-json prs.json --since ... --until ...

    # also write the e-mail version (HTML with inline styles, absolute links)
    python3 scripts/weekly_update.py --email ~/Downloads

Needs the GitHub CLI (`gh`) unless --from-json is given. Standard library only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import html
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = "Ansible-Automated-Compliance/aac"
REPO_URL = f"https://github.com/{REPO}"
ROOT = Path(__file__).resolve().parent.parent
UPDATES_DIR = ROOT / "docs" / "updates"
INDEX_BEGIN = "<!-- updates:begin (generated by scripts/weekly_update.py) -->"
INDEX_END = "<!-- updates:end -->"

# heading -> conventional-commit types, in the order the update prints them
SECTIONS = [
    ("New", ("feat",)),
    ("Fixed", ("fix", "perf", "revert")),
    ("Policy library", ("policies",)),
    ("Install and documentation", ("docs", "install")),
    ("Maintenance", ("chore", "ci", "build", "test", "refactor", "style")),
]
OTHER = "Other changes"
TITLE_RE = re.compile(r"^(?P<type>[a-z]+)(?:\((?P<scope>[^)]*)\))?(?P<breaking>!)?:\s*(?P<text>.+)$")
BOTS = ("dependabot", "renovate", "github-actions")


def is_dependency_bump(pr: dict) -> bool:
    login = ((pr.get("author") or {}).get("login") or "").lower()
    labels = {(label.get("name") or "").lower() for label in pr.get("labels") or []}
    return any(bot in login for bot in BOTS) or "dependencies" in labels


def classify(title: str) -> tuple[str, str, bool]:
    """Return (heading, text to print, breaking?) for a pull request title."""
    match = TITLE_RE.match(title.strip())
    if not match:
        return OTHER, title.strip(), False
    kind, scope, text = match["type"], (match["scope"] or "").strip(), match["text"].strip()
    breaking = bool(match["breaking"])
    if kind == "chore" and scope == "policies":
        kind = "policies"
    heading = next((name for name, kinds in SECTIONS if kind in kinds), OTHER)
    if re.match(r"[a-z]+(\s|$)", text):  # a plain word; identifiers such as winrm_eventlog keep their case
        text = text[:1].upper() + text[1:]
    if scope and kind != "policies":
        text = f"**{scope}:** {text}"
    return heading, text, breaking


def merged_date(pr: dict) -> dt.date:
    return dt.datetime.fromisoformat(pr["mergedAt"].replace("Z", "+00:00")).astimezone(dt.timezone.utc).date()


def in_window(pr: dict, since: dt.date, until: dt.date) -> bool:
    """since is exclusive, until inclusive: consecutive weekly windows never overlap or leave a gap."""
    return bool(pr.get("mergedAt")) and since < merged_date(pr) <= until


def render(prs: list[dict], since: dt.date, until: dt.date) -> str:
    prs = sorted((p for p in prs if in_window(p, since, until)), key=lambda p: (p["mergedAt"], p["number"]))
    bumps = [p for p in prs if is_dependency_bump(p)]
    grouped: dict[str, list[str]] = {}
    breaking: list[str] = []
    for pr in prs:
        if pr in bumps:
            continue
        heading, text, is_breaking = classify(pr["title"])
        line = f"- {text} ([#{pr['number']}]({REPO_URL}/pull/{pr['number']}))"
        grouped.setdefault(heading, []).append(line)
        if is_breaking:
            breaking.append(line)

    first = since + dt.timedelta(days=1)
    out = [
        f"# AAC weekly update: {until.isoformat()}",
        "",
        f"Changes merged to `main` from {first.isoformat()} to {until.isoformat()} (UTC): "
        f"{len(prs) - len(bumps)} pull requests, {len(bumps)} dependency updates.",
        "",
    ]
    if len(prs) == len(bumps):
        out += ["No feature or fix was merged in this window.", ""]
    if breaking:
        out += ["## Needs action when you update", "", *breaking, ""]
    for heading in [name for name, _ in SECTIONS] + [OTHER]:
        if grouped.get(heading):
            out += [f"## {heading}", "", *grouped[heading], ""]
    if bumps:
        numbers = ", ".join(f"[#{p['number']}]({REPO_URL}/pull/{p['number']})" for p in bumps)
        out += ["## Dependency updates", "", f"{len(bumps)} merged: {numbers}.", ""]
    out += [
        "## Details and requests",
        "",
        "- Each line links to its pull request. The full text of every change is in "
        "[CHANGELOG.md](../../CHANGELOG.md).",
        f"- To ask for a feature, a change or a report: [open a request]({REPO_URL}/issues/new/choose).",
        "- Earlier updates and how to subscribe: [docs/updates](README.md).",
        "",
    ]
    return "\n".join(out)


def subject(until: dt.date) -> str:
    return f"AAC weekly update: {until.isoformat()}"


_FONT = "font-family:-apple-system,'Segoe UI',Helvetica,Arial,sans-serif;color:#1f2328;"
_STYLE = {
    "h1": f"{_FONT}font-size:22px;margin:0 0 12px 0;",
    "h2": f"{_FONT}font-size:16px;margin:22px 0 6px 0;padding-bottom:4px;border-bottom:1px solid #d0d7de;",
    "p": f"{_FONT}font-size:14px;line-height:1.5;margin:0 0 10px 0;",
    "ul": f"{_FONT}font-size:14px;line-height:1.5;margin:0 0 10px 0;padding-left:22px;",
    "li": "margin:0 0 6px 0;",
    "a": "color:#0969da;text-decoration:none;",
    "code": "font-family:Menlo,Consolas,monospace;font-size:13px;background:#f1f3f5;padding:1px 4px;border-radius:3px;",
}


def _inline(text: str) -> str:
    """Escape one line of the update and turn its links, bold and code spans into HTML."""
    out = html.escape(text, quote=False)

    def link(match: re.Match) -> str:
        url = match[2]
        if not url.startswith("http"):  # a path inside the repo: an e-mail needs the full address
            path = "docs/updates/" + url if "/" not in url else url.replace("../../", "")
            url = f"{REPO_URL}/blob/main/{path}"
        return f'<a href="{url}" style="{_STYLE["a"]}">{match[1]}</a>'

    out = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link, out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    return re.sub(r"`([^`]+)`", rf'<code style="{_STYLE["code"]}">\1</code>', out)


def to_email_html(markdown: str) -> str:
    """The update as an HTML fragment with inline styles, which is what mail clients keep."""
    parts: list[str] = []
    items: list[str] = []

    def flush() -> None:
        if items:
            parts.append(f'<ul style="{_STYLE["ul"]}">' + "".join(items) + "</ul>")
            items.clear()

    for line in markdown.splitlines():
        if line.startswith("- "):
            items.append(f'<li style="{_STYLE["li"]}">{_inline(line[2:])}</li>')
            continue
        flush()
        if line.startswith("## "):
            parts.append(f'<h2 style="{_STYLE["h2"]}">{_inline(line[3:])}</h2>')
        elif line.startswith("# "):
            parts.append(f'<h1 style="{_STYLE["h1"]}">{_inline(line[2:])}</h1>')
        elif line.strip():
            parts.append(f'<p style="{_STYLE["p"]}">{_inline(line)}</p>')
    flush()
    return '<div style="max-width:720px;">\n' + "\n".join(parts) + "\n</div>\n"


def fetch(since: dt.date) -> list[dict]:
    cmd = [
        "gh", "pr", "list", "--repo", REPO, "--state", "merged", "--limit", "500",
        "--search", f"merged:>={since.isoformat()}",
        "--json", "number,title,mergedAt,author,labels",
    ]
    return json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)


def update_index(index: Path) -> None:
    """Rewrite the list of updates between the two markers in docs/updates/README.md."""
    if not index.exists():
        return
    text = index.read_text()
    if INDEX_BEGIN not in text or INDEX_END not in text:
        return
    files = sorted((p for p in index.parent.glob("20??-??-??.md")), reverse=True)
    lines = [f"- [{p.stem}]({p.name})" for p in files] or ["- No update published yet."]
    head, rest = text.split(INDEX_BEGIN, 1)
    tail = rest.split(INDEX_END, 1)[1]
    index.write_text(f"{head}{INDEX_BEGIN}\n" + "\n".join(lines) + f"\n{INDEX_END}{tail}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--until", type=dt.date.fromisoformat, help="last day of the window, inclusive (default: today, UTC)")
    parser.add_argument("--since", type=dt.date.fromisoformat, help="day before the first day of the window (default: until minus 7 days)")
    parser.add_argument("--from-json", type=Path, help="read pull requests from a saved `gh pr list --json` file")
    parser.add_argument("--stdout", action="store_true", help="print the update instead of writing it")
    parser.add_argument("--out-dir", type=Path, default=UPDATES_DIR)
    parser.add_argument("--email", type=Path, metavar="DIR", help="also write the e-mail version to DIR/AAC-weekly-update-<until>.html")
    args = parser.parse_args(argv)

    until = args.until or dt.datetime.now(dt.timezone.utc).date()
    since = args.since or until - dt.timedelta(days=7)
    if since >= until:
        parser.error("--since must be before --until")

    prs = json.loads(args.from_json.read_text()) if args.from_json else fetch(since)
    text = render(prs, since, until)
    if args.email:
        mail = args.email.expanduser() / f"AAC-weekly-update-{until.isoformat()}.html"
        mail.write_text(
            f'<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><title>{subject(until)}</title></head>\n'
            f"<body>\n{to_email_html(text)}</body></html>\n"
        )
        print(f"wrote {mail} (subject: {subject(until)})", file=sys.stderr)
    if args.stdout:
        sys.stdout.write(text)
        return 0
    args.out_dir.mkdir(parents=True, exist_ok=True)
    target = args.out_dir / f"{until.isoformat()}.md"
    target.write_text(text)
    update_index(args.out_dir / "README.md")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
