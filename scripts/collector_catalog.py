#!/usr/bin/env python3
"""Check the collector catalog and write the table in collectors/README.md.

collectors/catalog.yml lists every way AAC gathers state for policy evaluation.
This script keeps it true:

    python3 scripts/collector_catalog.py --check   # exit 1 on any problem
    python3 scripts/collector_catalog.py --write   # regenerate collectors/README.md

--check fails when a listed path does not exist, when a file that looks like a
collector is neither listed nor explained under not_collectors, or when
collectors/README.md is out of date.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "collectors" / "catalog.yml"
README = ROOT / "collectors" / "README.md"
BEGIN = "<!-- collectors:begin (generated by scripts/collector_catalog.py) -->"
END = "<!-- collectors:end -->"

SOURCES = {
    "in_repo": "Collectors in this repository",
    "integration": "Integrations: another product reads, AAC takes the results",
}
REQUIRED = ("id", "target", "source", "how", "reach", "uses", "paths", "stores", "feeds")

# A file matching one of these is a collector unless not_collectors says why not.
COLLECTOR_GLOBS = (
    "ansible/playbooks/*assess*.yml",
    "ansible/playbooks/*gather*.yml",
    "ansible/playbooks/*collect*.yml",
    "ansible/playbooks/*ingest*.yml",
    "ansible/playbooks/*audit*.yml",
    "ansible/tasks/collect_*.yml",
    "ansible/roles/aac_facts_collector/tasks/*.yml",
    "collections/ansible_collections/*/*/plugins/modules/*.py",
    "collections/ansible_collections/*/*/plugins/event_source/*.py",
    "collections/ansible_collections/*/*/roles/gather_*",
    "extensions/eda/plugins/event_source/*.py",
)


def load(path: Path = CATALOG) -> dict:
    return yaml.safe_load(path.read_text())


def problems(catalog: dict, root: Path = ROOT) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    covered: list[str] = []
    for entry in catalog.get("collectors") or []:
        name = entry.get("id", "<no id>")
        missing = [field for field in REQUIRED if not entry.get(field)]
        if missing:
            out.append(f"{name}: missing {', '.join(missing)}")
            continue
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
            out.append(f"{name}: id must be lower_snake_case")
        if name in seen:
            out.append(f"{name}: listed twice")
        seen.add(name)
        if entry["source"] not in SOURCES:
            out.append(f"{name}: source must be one of {', '.join(SOURCES)}")
        for path in entry["paths"]:
            if not (root / path).exists():
                out.append(f"{name}: path does not exist: {path}")
            covered.append(path.rstrip("/"))
    for item in catalog.get("not_collectors") or []:
        path = item.get("path", "")
        if not item.get("reason"):
            out.append(f"not_collectors: {path or '<no path>'} has no reason")
        if not (root / path).exists():
            out.append(f"not_collectors: path does not exist: {path}")
        covered.append(path.rstrip("/"))

    def is_covered(rel: str) -> bool:
        return any(rel == path or rel.startswith(path + "/") for path in covered)

    for pattern in COLLECTOR_GLOBS:
        for found in sorted(root.glob(pattern)):
            rel = found.relative_to(root).as_posix()
            if found.name.startswith("__") or is_covered(rel):
                continue
            out.append(f"not in the catalog: {rel} (add it to a collector, or to not_collectors with a reason)")
    return out


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def table(catalog: dict) -> str:
    lines: list[str] = []
    entries = catalog.get("collectors") or []
    for source, heading in SOURCES.items():
        rows = [entry for entry in entries if entry["source"] == source]
        if not rows:
            continue
        lines += [f"### {heading}", "", "| Target | How the facts are gathered | Reached by | Where | Stored in |", "|---|---|---|---|---|"]
        for entry in rows:
            where = "<br>".join(f"[`{Path(p).name}`](../{p})" for p in entry["paths"])
            lines.append(
                f"| {_cell(entry['target'])} | {_cell(entry['how'])} | {_cell(entry['reach'])} | {where} | {_cell(entry['stores'])} |"
            )
        lines.append("")
    count = len(entries)
    lines.append(f"{count} collectors: {sum(e['source'] == 'in_repo' for e in entries)} in this repository, "
                 f"{sum(e['source'] == 'integration' for e in entries)} integrations.")
    return "\n".join(lines)


def rendered(catalog: dict, readme: str) -> str:
    head, rest = readme.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    return f"{head}{BEGIN}\n{table(catalog)}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail on any problem, including a stale README table")
    mode.add_argument("--write", action="store_true", help="regenerate the table in collectors/README.md")
    args = parser.parse_args(argv)

    catalog = load()
    found = problems(catalog)
    text = README.read_text()
    if args.write:
        README.write_text(rendered(catalog, text))
    elif rendered(catalog, text) != text:
        found.append("collectors/README.md is out of date: run python3 scripts/collector_catalog.py --write")
    for line in found:
        print(line, file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
